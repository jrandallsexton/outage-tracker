// Builds the app's address list from the hand-curated master list.
//
//   input:  data/addresses-raw.csv   (edit this file to fix/confirm addresses)
//   output: src/data/addresses.json  (what the app's address picker loads)
//           data/review.md           (everything that still needs a human check)
//
// Status values in the CSV:
//   confirmed   number clearly labeled on a lot, street clear
//   inferred    lot visible but number/street deduced from neighbors   -> included
//   label_only  number label but no building drawn (vacant lot?)       -> included
//   unclear     not enough info; needs a check in Google Maps          -> NOT included
//   excluded    stray label (on a road, in a park, etc.)               -> NOT included
//
// Run: node scripts/build-addresses.mjs
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const RAW = join(root, 'data', 'addresses-raw.csv');
const OUT_JSON = join(root, 'src', 'data', 'addresses.json');
const OUT_REVIEW = join(root, 'data', 'review.md');
const COVERAGE = join(root, 'data', 'coverage-notes.md');
const ESTIMATED_HOMES = 751;
const INCLUDED = new Set(['confirmed', 'inferred', 'label_only']);
const STATUSES = new Set([...INCLUDED, 'unclear', 'excluded']);

function parseCsv(text) {
  const out = [];
  let row = [], field = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') q = false;
      else field += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); field = '';
      if (row.some(f => f !== '')) out.push(row);
      row = [];
    } else field += c;
  }
  if (field !== '' || row.length) { row.push(field); out.push(row); }
  const [header, ...data] = out;
  return data.map(r => Object.fromEntries(header.map((h, i) => [h.trim(), (r[i] ?? '').trim()])));
}

const rows = parseCsv(readFileSync(RAW, 'utf8'));
const errors = [];
rows.forEach((r, i) => {
  if (!STATUSES.has(r.status)) errors.push(`line ${i + 2}: unknown status "${r.status}"`);
  if (INCLUDED.has(r.status) && !/^\d+$/.test(r.number)) errors.push(`line ${i + 2}: included row needs a numeric number`);
});

const included = rows.filter(r => INCLUDED.has(r.status));
const seen = new Map();
for (const r of included) {
  const key = `${r.number}|${r.street.toLowerCase()}`;
  if (seen.has(key)) errors.push(`duplicate address: ${r.number} ${r.street}`);
  seen.set(key, r);
}
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }

const byStreetNum = (a, b) => a.street.localeCompare(b.street) || Number(a.number) - Number(b.number);
const slug = s => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const addresses = included.slice().sort(byStreetNum).map(r => ({
  id: `${r.number}-${slug(r.street)}`,
  number: Number(r.number),
  street: r.street,
  label: `${r.number} ${r.street}`,
}));
mkdirSync(dirname(OUT_JSON), { recursive: true });
writeFileSync(OUT_JSON, JSON.stringify(addresses, null, 2) + '\n');

// ---------- review.md ----------
const count = s => rows.filter(r => r.status === s).length;
const streets = [...new Set(included.map(r => r.street))].sort();
const L = [];
L.push('# Address review', '');
L.push('Generated by `node scripts/build-addresses.mjs` - do not edit by hand. Fix things in `data/addresses-raw.csv` and re-run.', '');
L.push('**Screenshot letters:** each screenshot file starts with its letter. **A-J** are in `media/` (e.g. `media/C_2026-11-17_13h06_50.png`) and **K-S** are in `media/round2/`, and **T** is in `media/round3/`. Name new screenshots starting from **U** so they are easy to cite.', '');
L.push('## Summary', '');
L.push(`- **Addresses in the app list:** ${addresses.length} (estimate: ~${ESTIMATED_HOMES}, so about ${ESTIMATED_HOMES - addresses.length} still unaccounted for)`);
L.push(`- confirmed: ${count('confirmed')} | inferred: ${count('inferred')} | label_only: ${count('label_only')} | unclear (left out): ${count('unclear')} | excluded: ${count('excluded')}`, '');
L.push('| Street | Homes | Odd numbers | Even numbers |', '|---|---:|---|---|');
for (const s of streets) {
  const nums = included.filter(r => r.street === s).map(r => Number(r.number));
  const span = arr => arr.length ? `${Math.min(...arr)}-${Math.max(...arr)} (${arr.length})` : '-';
  L.push(`| ${s} | ${nums.length} | ${span(nums.filter(n => n % 2))} | ${span(nums.filter(n => !(n % 2)))} |`);
}
L.push('');

if (existsSync(COVERAGE)) L.push(readFileSync(COVERAGE, 'utf8').trim(), '');

L.push('**How to report findings:** type what you found in the **Your finding** column of any table below.',
  'Before the next rebuild, Claude copies your findings into the `verified` column of `data/addresses-raw.csv`',
  '(this file is regenerated, so the CSV is where they are kept), and they show up here again.', '');
const cell = s => (s || '').replace(/\|/g, '\\|');
const section = (title, blurb, list, { showStatus = false } = {}) => {
  L.push(`## ${title}`, '', blurb, '');
  if (!list.length) { L.push('_None._', ''); return; }
  L.push(`| Address |${showStatus ? ' Status |' : ''} Screenshots | Note | Your finding |`,
    `|---|${showStatus ? '---|' : ''}---|---|---|`);
  for (const r of list.slice().sort(byStreetNum))
    L.push(`| ${r.number} ${r.street} |${showStatus ? ` ${r.status} |` : ''} ${r.source} | ${cell(r.note)} | ${cell(r.verified)} |`);
  L.push('');
};
section('1. Unclear - please check in Google Maps (NOT in the app list yet)',
  'Look each one up and write the real address (or "not a home") in **Your finding**.',
  rows.filter(r => r.status === 'unclear'));
section('2. Inferred - in the app list, but worth a quick check',
  'The lot is visible but its number (or street) was deduced from the neighboring numbers.',
  rows.filter(r => r.status === 'inferred'));
section('3. Label only - in the app list, possibly vacant lots',
  'A number is shown but no building is drawn. Change to `excluded` if no one lives there.',
  rows.filter(r => r.status === 'label_only'));
section('4. Excluded stray labels', 'Labels that are not homes. Listed so nothing is lost silently.',
  rows.filter(r => r.status === 'excluded'));
section('5. Verified by you', 'Everything you have checked so far, for the record.',
  rows.filter(r => r.verified), { showStatus: true });

L.push('## 6. Numbering gaps', '');
L.push('Each street has odd numbers on one side and even on the other. These are numbers skipped in a sequence.',
  'Most are intersections, curves or wider lots; a gap can also mean a missed lot. Gaps of 10+ numbers usually mean the area was not in the screenshots.', '');
for (const s of streets) {
  const nums = included.filter(r => r.street === s).map(r => Number(r.number));
  const parts = [];
  for (const parity of [1, 0]) {
    const seq = nums.filter(n => n % 2 === parity).sort((a, b) => a - b);
    for (let i = 1; i < seq.length; i++) {
      if (seq[i] - seq[i - 1] > 2) {
        const missing = [];
        for (let n = seq[i - 1] + 2; n < seq[i]; n += 2) missing.push(n);
        parts.push(missing.length > 4 ? `${missing[0]}-${missing.at(-1)} (${missing.length})` : missing.join(', '));
      }
    }
  }
  if (parts.length) L.push(`- **${s}:** ${parts.join('; ')}`);
}
L.push('');
writeFileSync(OUT_REVIEW, L.join('\n'));

console.log(`addresses.json: ${addresses.length} addresses on ${streets.length} streets`);
console.log(`review.md: ${count('unclear')} unclear, ${count('inferred')} inferred, ${count('label_only')} label-only, ${count('excluded')} excluded`);
